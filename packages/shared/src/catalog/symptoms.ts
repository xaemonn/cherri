export type SymptomCode = (typeof SYMPTOMS)[number]['code'];

export const SYMPTOM_CODES = SYMPTOMS.map((s) => s.code) as [SymptomCode, ...SymptomCode[]];

const SYMPTOM_BY_CODE = new Map<string, SymptomDef>(SYMPTOMS.map((s) => [s.code, s]));

export function getSymptom(code: string): SymptomDef | undefined {
  return SYMPTOM_BY_CODE.get(code);
}

export function symptomLabel(code: string): string {
  return SYMPTOM_BY_CODE.get(code)?.label ?? code;
}
