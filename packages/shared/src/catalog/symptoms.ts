export const SYMPTOM_CATEGORIES = ['PAIN', 'BLEEDING', 'DIGESTION', 'SKIN_HAIR', 'MOOD', 'ENERGY_SLEEP', 'BODY', 'PREGNANCY'] as const;
export type SymptomCategory = (typeof SYMPTOM_CATEGORIES)[number];

/** Categories only offered in some life stages; every other category is always shown. */
const CATEGORY_STAGES: Partial<Record<SymptomCategory, readonly LifeStage[]>> = { PREGNANCY: ['PREGNANCY'] };

export function symptomCategoriesFor(stage: LifeStage): SymptomCategory[] {
  return SYMPTOM_CATEGORIES.filter((c) => CATEGORY_STAGES[c]?.includes(stage) ?? true);
}

